CREATE TABLE IF NOT EXISTS public.article_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  article_id text NOT NULL,
  reason text NOT NULL CHECK (reason IN ('image', 'title', 'duplicate', 'other')),
  title text,
  source text,
  category text,
  image text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS article_reports_article_id_idx ON public.article_reports (article_id);
CREATE INDEX IF NOT EXISTS article_reports_created_at_idx ON public.article_reports (created_at DESC);
ALTER TABLE public.article_reports ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.article_reports TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.article_reports_id_seq TO service_role;

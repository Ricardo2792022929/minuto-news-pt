ALTER TABLE public.articles
  ADD COLUMN IF NOT EXISTS image_status text NOT NULL DEFAULT 'original'
    CHECK (image_status IN ('original', 'search', 'provisional')),
  ADD COLUMN IF NOT EXISTS image_candidates jsonb NOT NULL DEFAULT '[]'::jsonb;

CREATE TABLE IF NOT EXISTS public.image_api_metrics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service text NOT NULL,
  requests integer NOT NULL DEFAULT 0,
  results_found integer NOT NULL DEFAULT 0,
  accepted integer NOT NULL DEFAULT 0,
  failures integer NOT NULL DEFAULT 0,
  latency_ms integer NOT NULL DEFAULT 0,
  rejection_reasons jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.image_api_metrics ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.image_api_metrics TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.image_api_metrics_id_seq TO service_role;
